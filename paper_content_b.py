("h1", "8. Conclusion"),

("p",
 "The formulation of new provinces in Pakistan is neither the constitutional dead end its critics in "
 "Parliament claim nor the governance free lunch its claimants promise. It is a *deliberately hard "
 "consensus instrument* - Article 239 plus the affected-assembly veto of clause (4) - that Pakistan's "
 "founders designed to make territorial change slow precisely so that it would be legitimate, and that "
 "the polity has used, when it has used it at all, with a record of genuine success (1970 re-regionalization "
 "within the eventual 1973 settlement; the 18th Amendment; the 2018 FATA merger) and genuine failure "
 "(One Unit imposed; devolution imposed; packages substituted indefinitely for consent) [1][4][36]. "
 "The challenges of the 2020s are real and partly decisive: no current majority reaches two-thirds of "
 "three assemblies across four parties in two governments; the divisible pool is fixed and its floor "
 "constitutional; water and royalties are settled between provinces and would be unsettled by splitting "
 "them; and two claimant regions are conflict theatres where border-making has historically multiplied "
 "violence rather than dividing it [18][20][32][60]."),

("p",
 "The prospects, nonetheless, are now historically material in a way they were not before 2023: a digital "
 "census and an empowered election machinery make the arithmetic auditable; the 18th Amendment's devolution "
 "makes a new province a real prize for its citizens rather than merely a real office for its elites; and "
 "the comparative record shows that re-scaling pacifies when it is rule-bound, sequenced and funded from "
 "outside the zero-sum, and radicalizes when it is not [23][25][26][70][71]. The design agenda - "
 "local-government compliance first; one consensual amending convention; pre-committed viability criteria; "
 "a generalization of the Article 160(3A) floor plus transitional federal money; Senate and CCI "
 "re-engineering; settlement commissions for canals, gas and cadres; and a shortlist of cases (Hazara "
 "first, then South Punjab; Karachi as metropolitan settlement; Balochistan last and only with a "
 "political settlement) - is not a recipe for creating provinces quickly. It is the only recorded way "
 "to create them *safely*, and thus the only way their benefits - shorter chains between taxpayers and "
 "treasuries, formula rather than favour in allocation, recognition without secession - are likely to "
 "survive the first electoral cycle."),

("p",
 "A final qualification. This paper has argued that the deepest problem of Pakistan's federation is not "
 "the number of its provinces but the *currency* of their relationship: transfers without taxation, "
 "elections without tiers, consent by arithmetic rather than architecture. On current trajectory, a "
 "28th Amendment - if it comes - will be a bargaining table at which small fixes to large problems are "
 "traded for coalition votes, and new provinces will be born half-designed, like the merged districts "
 "were, but without their one virtue: a funded plan. The alternative available to Pakistan's politics in "
 "2026-29 is to make the provincial question *legible* - criteria, commissions, census, cadence - so "
 "that when the moment of consensus comes, as it came in 1973 and in 2010, the state does not have to "
 "improvise with a map. Pakistan has survived every provincial reorganization of its first seventy-five "
 "years. It will survive this one only if, for the first time, the reorganization is *by design*. The "
 "formulation of new provinces is, in the end, the formulation of the state's willingness to be fair in "
 "public, in advance, when it hurts least. The evidence reviewed here suggests Pakistan has finally built "
 "the instruments to do so - and has not yet built the politics."),

