("p",
 "The strongest case for new provinces is not ethnic but statistical. The UNDP's canonical mapping of "
 "Pakistan's human development found a contiguous 'deprivation divide' running through the country's "
 "south and west - southern Punjab, interior Sindh, the merged districts, and all but the Quetta-Kalat "
 "corridor of Balochistan - in which poverty, child mortality and out-of-school rates resembled the "
 "region's poorer neighbors more than they resembled Lahore or Islamabad [11]; PSLM multidimensional "
 "poverty mapping has since placed several southern Punjab and south Sindhi districts among the ten worst "
 "of all 160+ districts [73]. The distance between a Multan tehsil and a Lahore secretariat is the same "
 "as between Berlin and Rome; a resident of Rajanpur reaches the deputy commissioner's office, a "
 "district sessions judge and a teaching hospital in hours that a resident of Gulberg also reaches in "
 "hours - but the *budgetary* distance is enormous, because discretionary allocations cluster where "
 "capacities and political gravity cluster. The mover of the 2024 Senate bill reduced the claim to one "
 "statistic: of Punjab's 50,112 government schools, 13,446 are in the south - a share below its share "
 "of pupils, students and infants [38]. Comparative evidence says a smaller, nearer provincial state "
 "reduces that bias: Faguet's Bolivia finding - that decentralization produced a systematic reallocation "
 "of public investment toward poor provinces' health and education within a few years - is the best "
 "quasi-experimental analogue available, and the Indonesia district-creation literature shows the same "
 "redistributive reflex (with, equally, the same capture risk) [17][16][25]. Pakistan's own quasi-"
 "experiment - the ring-fenced 33 percent of provincial PSDP for South Punjab, the Rs581 billion federal "
 "package, the additional secretariat at Multan - reports a doubling of sanctioned health and education "
 "budget lines in the south's districts since 2018 [42][45]. If ring-fencing *without* sovereignty moves "
 "money this much, sovereignty plausibly moves it more - and, once devolved, moves it through formula "
 "rather than through the goodwill of the chief minister who announced it."),

("h2", "6.2 Conflict accommodation and the recognition dividend"),

("p",
 "Federalism theory supplies the second and most underweighted argument. Riker's classic formulation - "
 "federalism as a bargain in which constituent units trade centralization of some functions for "
 "autonomy over others - implies that when a national community demands the status of a contracting "
 "party, refusing it is not neutral conservatism but an renegotiation of the federation's terms [13]; "
 "Elazar's 'compact' tradition adds that federations survive by renewing consent across generations "
 "[12]. Kymlicka's accommodation thesis and Toft's boundary studies converge on the same practical "
 "point: institutionally recognized self-rule for geographically concentrated groups - where criteria "
 "are rules-based and timing precedes escalation - is associated with *lower* separatist violence, "
 "whereas deferred recognition is associated with movement radicalization [19][18]. Pakistan's history "
 "is a case study: the 1970 re-creation of four provinces and the 1973 autonomy package de-escalated the "
 "Sindhi, Seraiki and Baloch movements for a decade (and the decade's reversal - dismissal of governments, "
 "One-Unit nostalgia in Punjab's administration - re-escalated them) [4][6][8]; the 18th Amendment is "
 "credited with a similar, ongoing dividend for Sindhi and Baloch cultural claims [22][10]. A *properly "
 "sequenced* province-creation program would extend that dividend: Hazara's unanimous host-assembly "
 "consent shows the consensual route is not theoretical [41]; the FATA merger shows the state can "
 "integrate a territory and its citizens' claims at the same time [35][31]; and a South Punjab created "
 "under formula, not patronage, would answer the Baloch-Pashtun 'recognition competition' by giving the "
 "state a credible template of *fair procedure* [18][20]. This is the difference between re-scaling as "
 "demobilization (India 1956, Sidama) and re-scaling as siege (Moradabad-to-Papua variants) - criteria "
 "first, claims later [23][26]."),

("h2", "6.3 Economic reconfiguration: growth poles, ports and the discipline question"),

("p",
 "The economic-federalism school's original proposal - Mumtaz Ahmad and Zaidi's 'economic federation' of "
 "some 45 fiscal communities organized around viability rather than ethnicity, with provinces as "
 "competitors for investment rather than claimants on the pool - remains the most serious structural "
 "answer to the size problem and remains untried [10][11]. Province-scale units could each run an "
 "investment desk, an urban authority, a port or an energy corridor policy that Punjab's 205,000 km2 "
 "bureaucracy currently cannot: a Makran province's entire administrative class would be Gwadar; a "
 "South Punjab's would be energy-agro industry (the Bahawalpur solar complex, the DG Khan-Industries belt, "
 "and gas-linked fertilizer chains are already there); a Karachi province would confront the city's "
 "parastatal fragmentation directly rather than through a Sindh assembly whose rural majorities vote "
 "against urban property-tax reform each time it is proposed. Qian and Weingast's market-preserving "
 "federalism gives the theoretical test - hard budget constraints, factor mobility, no bailouts [15] - "
 "and Pakistan flunks it today: provinces are transfer-dependents, not revenue-raisers, and the real "
 "constraint on Karachi's or Gwadar's economics is not the size of the province that administers them but "
 "the absence of any fiscal discipline at any level [14][16]. The realistic prospect is therefore the "
 "'second-best' one used in India's post-1956 settlements and Indonesia's viability law: new units enter "
 "with *pre-committed fiscal duties* (own-revenue floors, assembly-size caps, borrowing rules via "
 "Article 218A's CCI approval [1]), and the federation uses the split as leverage to complete the "
 "revenue-devolution that the 7th NFC left half-done (provincial sales taxes on services now finance "
 "single-digit shares; combined own-source collection runs at roughly an eighth of transfers) [30][47][48]."),

