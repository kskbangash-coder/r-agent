("h1", "7. Design Principles and Policy Options"),

("p",
 "This section translates the challenge and prospect analysis into a design agenda a 28th-style "
 "amendment (or any future tranche) could adopt. The organizing rule is *rules before reals*: criteria, "
 "formulae and settlement machinery fixed ex ante, then applied to specific cases, in the sequence "
 "Indonesia's and India's settlements used and Pakistan's 2022 draft bill lacked [26][23][39]."),

("p",
 "**(1) Sequence the ladder; start at the rung that is already constitutional.** Article 140A is now "
 "self-executing in intent: ECP-conducted local-government elections within the constitutionally "
 "contemplated window, with hearings against assemblies that default (the ECP's 2026 pressure on Punjab, "
 "KP and the capital is the mechanism finding its teeth) [33][52][53][54]. No new province before every "
 "existing province has completed two local-government cycles with devolved functions and provincial "
 "finance commissions; failure of the weakest tier of government is the strongest argument against "
 "proliferating the strongest ones. The intermediate rung - directly elected divisional councils with "
 "delegated provincial functions (schools, PHCs, tehsil revenue, divisional police oversight) - converts "
 'the "province" debate into a devolution competition whose results are measurable within one term.'),

("p",
 "**(2) One consensual amending convention, not serial arithmetic.** If province creation proceeds, it "
 "proceeds as a single negotiated package under the 18th Amendment's precedent - all-party conference, "
 "published technical base data, two-thirds in both houses and the affected assemblies - not as a "
 "government bill passed against a boycotting opposition as the 26th and 27th Amendments were [33][34][40]. "
 "The package should include its own *new-units clause* (a dedicated Article 239A or a schedule), "
 "ending the textualist quarrel over whether 'altering limits' covers 'creating provinces,' with the "
 "affected-assembly supermajority retained [40][1]."),

("p",
 "**(3) Pre-committed viability criteria (the Indonesia model, adapted).** A statutory test - area, "
 "population, ten-year fiscal self-sufficiency prospect, administrative capacity, and a national-integrity "
 "and security clause - applied by an independent boundary commission before any unit is named [26]. "
 "Criteria should *not* include ethnic-core tests as disqualifiers (that is Ethiopia's road [24][70]) but "
 "should include Toft's demographic-coherence and mixed-district rules (a unit may not exceed an agreed "
 "share of any other identity's demographic core) [18]."),

("p",
 "**(4) Break the zero-sum, honestly and temporarily.** Transitional funding flows *from the federation, "
 "outside the divisible pool*, on the FATA action-plan model - sunset at 10-15 years, audited annually, "
 "and not counted in the receiving units' NFC baselines [31]; the Article 160(3A) non-regression floor is "
 "generalized into a *residual-province floor* (a successor of a split province cannot be pushed below its "
 "pre-split per-capita real transfer for the transition) [1][30]; and every new unit enters with "
 "assembly-size caps, a civil-service absorption formula (no net cadre increase above a fixed fraction), "
 "and a borrowing rule policed by the CCI under Article 218A [1][50]. A 'one-time settlement' - the phrase "
 "Pakistan used for the 1947 and Kalat questions - is the wrong precedent for assets and the right one for "
 "water: a standing Inter-Provincial Settlement Commission (retired-chief-justice chaired, expert-secretariat "
 "backed) adjudicates the division of canal entitlements, Sui-system royalties (Art. 158), assets, "
 "liabilities and pensions *before* consent votes, with the 1991 Indus accord's provincial entitlements "
 "declared inviolable by intra-province reorganization - so Sindh never litigates a split it did not "
 "choose [32][60][63][64]."),

("p",
 "**(5) Re-engineer the Senate and CCI for more than four members.** Options, in ascending cost: "
 "(a) enlarge the Senate as the 2022 bill drafted (96 to 119; staggered classes), keeping *unit parity* "
 "- every province equal, new units small - which preserves the doctrine smaller provinces will not trade "
 "[39][38]; (b) a two-tier upper house on Swiss lines: 2 senators per founding province, 1 per successor "
 "unit and 1 per union territory, so the aggregate of successors equals the mother unit (a 'half-canton' "
 "device); (c) CCI reform - chief minister of every unit, with qualified-majority plus *affected-province "
 "veto* on water, energy and census-linked matters, and the NFC floor made formula-bound rather than "
 "negotiation-bound [1][47][48]. Whatever is chosen, the Senate must not become a chamber where the nine "
 "largest identities outvote the four smallest."),

("p",
 "**(6) Make representation arithmetic transparent and automatic.** NA and assembly seats for any new "
 "unit derive from the current census and the existing apportionment rules; first elections coincide with "
 "the next general cycle to avoid expensive by-election logistics [2][51]; reserved-seat floors for women "
 "and minorities *rise* with unit count (the 2022 bill's four-to-five minority bump is a template) [39]; "
 "and the ECP gains a member from each new unit, as drafted [39]."),

("p",
 "**(7) Prioritize cases with clean borders and consenting hosts.** The shortlist that satisfies (3)-(5) "
 "*today* is short: Hazara (existing division; unanimous host resolution [41]) and South Punjab (existing "
 "three divisions, drafted bill, host-assembly resolution history [39][38]) - sequenced one after the "
 "other, not simultaneously. Karachi enters as a *metropolitan settlement* under the 140A architecture "
 "with fiscal powers (property tax harmonization, city-manager with police liaison), revisited as a "
 "province only if Sindh's assembly consents [32][51]; Balochistan units (Kalat, Makran, the Pashtun "
 "belt) are held for a *post-settlement* constitutional process that follows the missing-persons and "
 "political-prisoner agenda - a boundary commission without a cease-fire framework would reproduce "
 "Pakistan's worst 1970s memory [8][43][20]. Potohar and Bahawalpur join the shortlist only if a criteria "
 "law pre-commits to multiple Punjab successors in the same tranche, breaking the 'punishment split' "
 "optics [40][55]."),

("p",
 "**(8) Institutionalize the package model's good parts.** Where provinces are not created, the ring-"
 "fenced package + additional-secretariat machinery (33 percent of PSDP, Multan secretariat, ECP-ready "
 "divisional offices) should be written into statute with KPIs, sunsets and audit - not left as the "
 "chief minister's announcement of the month [42][45][74]. Done this way, the 'package' becomes Phase 0 "
 "of a ladder rather than a permanent substitute for consent; done the other way, it becomes the next "
 "grievance - and the cycle renews itself, as it has every decade since Chester told Ayub, in 1964, "
 "that the map had to move [5]."),

